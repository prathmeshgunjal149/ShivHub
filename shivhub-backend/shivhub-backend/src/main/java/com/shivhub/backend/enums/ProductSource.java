package com.shivhub.backend.enums;

/*
 * =========================================================
 * ProductSource
 * =========================================================
 *
 * Identifies who created the product.
 *
 * SELLER
 *  -> Product added by a seller.
 *
 * ADMIN
 *  -> Product added directly by ShivHub Admin.
 *
 * =========================================================
 */

public enum ProductSource {

    SELLER,

    ADMIN
}