package com.shivhub.backend.enums;

/*
 * Role defines the different types of users
 * available in ShivHub.
 *
 * CUSTOMER → Normal customer who purchases products
 * SELLER   → Approved seller who sells products
 * ADMIN    → ShivHub administrator
 */

public enum Role {

    CUSTOMER,
    SELLER,
    STAFF,
    ADMIN
}
